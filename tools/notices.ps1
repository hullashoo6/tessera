# Regenerates THIRD_PARTY_NOTICES.md from what is actually built:
# Rust crates compiled into the Windows and macOS apps (cargo metadata),
# the interface's npm runtime packages, and the website's fonts.
# Flags licences that would need special handling (copyleft).
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root
$crates = @{}
foreach ($target in 'x86_64-pc-windows-msvc', 'aarch64-apple-darwin', 'x86_64-apple-darwin') {
  $meta = cmd /c "cargo metadata --format-version 1 --locked --filter-platform $target 2>nul" | ConvertFrom-Json
  $members = @($meta.workspace_members)
  # Only packages reachable from the desktop app (not dev-only tools).
  $nodes = @{}; foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
  $desk = ($meta.packages | Where-Object { $_.name -eq 'tessera-desktop' }).id
  $seen = @{}; $stack = New-Object System.Collections.Stack; $stack.Push($desk)
  while ($stack.Count) {
    $id = $stack.Pop(); if ($seen[$id]) { continue }; $seen[$id] = $true
    foreach ($d in $nodes[$id].deps) {
      if ($d.dep_kinds | Where-Object { $_.kind -ne 'dev' }) { $stack.Push($d.pkg) }
    }
  }
  foreach ($p in $meta.packages) {
    if ($seen[$p.id] -and ($members -notcontains $p.id)) {
      $crates["$($p.name)@$($p.version)"] = $p
    }
  }
}
$npm = @()
$pkg = Get-Content apps/desktop/package.json -Raw | ConvertFrom-Json
foreach ($name in $pkg.dependencies.PSObject.Properties.Name) {
  $pj = Get-Content "apps/desktop/node_modules/$name/package.json" -Raw | ConvertFrom-Json
  $npm += [pscustomobject]@{ name = $name; version = $pj.version; license = "$($pj.license)" }
}
$copyleft = 'GPL|LGPL|AGPL|MPL|EPL|CDDL|EUPL|OSL|SSPL'
$flags = @()
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('# Third-party notices')
[void]$out.AppendLine('')
[void]$out.AppendLine('Tessera includes the open-source components below, used under their licences. Generated by `tools/notices.ps1` from the components actually built into the Windows and macOS apps; do not edit by hand.')
[void]$out.AppendLine('')
[void]$out.AppendLine("Generated: $((Get-Date).ToString('yyyy-MM-dd')). Rust crates: $($crates.Count). Interface packages: $($npm.Count).")
[void]$out.AppendLine('')
[void]$out.AppendLine('## Rust crates (desktop app)')
[void]$out.AppendLine('')
[void]$out.AppendLine('| Crate | Version | Licence | Source |')
[void]$out.AppendLine('|---|---|---|---|')
foreach ($k in ($crates.Keys | Sort-Object)) {
  $p = $crates[$k]
  $lic = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { 'UNKNOWN' }
  if ($lic -match $copyleft -and $lic -notmatch ' OR ') { $flags += "$k ($lic)" }
  if ($lic -eq 'UNKNOWN') { $flags += "$k (no licence metadata)" }
  $src = if ($p.repository) { $p.repository } else { "https://crates.io/crates/$($p.name)" }
  [void]$out.AppendLine("| $($p.name) | $($p.version) | $lic | $src |")
}
[void]$out.AppendLine('')
[void]$out.AppendLine('## Interface packages (npm)')
[void]$out.AppendLine('')
[void]$out.AppendLine('| Package | Version | Licence |')
[void]$out.AppendLine('|---|---|---|')
foreach ($n in ($npm | Sort-Object name)) {
  if ($n.license -match $copyleft) { $flags += "$($n.name) ($($n.license))" }
  [void]$out.AppendLine("| $($n.name) | $($n.version) | $($n.license) |")
}
[void]$out.AppendLine('')
[void]$out.AppendLine('## Website')
[void]$out.AppendLine('')
[void]$out.AppendLine('| Component | Licence |')
[void]$out.AppendLine('|---|---|')
[void]$out.AppendLine('| Fraunces (variable font, via @fontsource-variable) | SIL Open Font License 1.1 |')
[void]$out.AppendLine('| Instrument Sans (variable font, via @fontsource-variable) | SIL Open Font License 1.1 |')
[void]$out.AppendLine('| Astro (build tool, not shipped) | MIT |')
[void]$out.AppendLine('')
[void]$out.AppendLine('## Licence texts')
[void]$out.AppendLine('')
[void]$out.AppendLine('Each component''s full licence text is in its source repository listed above and in the copy downloaded by Cargo or npm. Common licences: MIT, Apache-2.0, BSD-2-Clause, BSD-3-Clause, ISC, Zlib, Unicode-3.0, CC0-1.0, MPL-2.0 (file-level; source available at the linked repository), SIL OFL 1.1.')
[IO.File]::WriteAllText((Join-Path $root 'THIRD_PARTY_NOTICES.md'), $out.ToString(), (New-Object Text.UTF8Encoding($false)))
"wrote THIRD_PARTY_NOTICES.md: $($crates.Count) crates, $($npm.Count) npm packages"
$byLic = $crates.Values | Group-Object { if ($_.license) { $_.license } else { 'UNKNOWN' } } | Sort-Object Count -Descending
$byLic | Select-Object -First 12 | ForEach-Object { "  $($_.Count)  $($_.Name)" }
if ($flags) { "NEEDS REVIEW:"; $flags | ForEach-Object { "  $_" } } else { 'No copyleft-only or unlicensed components.' }
