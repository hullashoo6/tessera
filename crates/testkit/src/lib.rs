//! Disposable filesystem fixtures.
//!
//! Everything here writes only beneath a directory the caller supplies
//! (normally a fresh temporary directory). Generated trees carry a marker
//! file so tooling can refuse to write into folders it did not create.

use std::fs::{self, File};
use std::io;
use std::path::{Path, PathBuf};

pub use tempfile;

/// Name of the marker file placed at the root of generated fixtures.
pub const MARKER: &str = ".tessera-fixture";

/// Deterministic SplitMix64 generator (no external RNG dependency, so
/// fixtures are identical on every platform and run).
#[derive(Debug, Clone)]
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Rng(seed)
    }
    pub fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
    /// Uniform in `lo..=hi`.
    pub fn range(&mut self, lo: u64, hi: u64) -> u64 {
        lo + self.next_u64() % (hi - lo + 1)
    }
}

/// Creates `rel` (and parents) under `root` with exactly `size` bytes of
/// logical length. Content is not written; length is set directly.
pub fn file(root: &Path, rel: impl AsRef<Path>, size: u64) -> io::Result<PathBuf> {
    let p = root.join(rel);
    if let Some(parent) = p.parent() {
        fs::create_dir_all(parent)?;
    }
    let f = File::create(&p)?;
    if size > 0 {
        f.set_len(size)?;
    }
    Ok(p)
}

/// Creates a file filled with real (non-zero) bytes, so it is fully
/// allocated on every filesystem.
pub fn dense_file(root: &Path, rel: impl AsRef<Path>, size: usize) -> io::Result<PathBuf> {
    let p = root.join(rel);
    if let Some(parent) = p.parent() {
        fs::create_dir_all(parent)?;
    }
    let data: Vec<u8> = (0..size).map(|i| (i % 251) as u8 + 1).collect();
    fs::write(&p, data)?;
    Ok(p)
}

pub fn dir(root: &Path, rel: impl AsRef<Path>) -> io::Result<PathBuf> {
    let p = root.join(rel);
    fs::create_dir_all(&p)?;
    Ok(p)
}

/// Parameters for a synthetic benchmark tree.
#[derive(Debug, Clone, Copy)]
pub struct GenSpec {
    pub files: u64,
    pub seed: u64,
    /// Average files per directory.
    pub files_per_dir: u64,
    /// Maximum subdirectories created per directory.
    pub fanout: u64,
}

impl GenSpec {
    pub fn new(files: u64) -> Self {
        GenSpec {
            files,
            seed: 0x7E55_E8A0,
            files_per_dir: 40,
            fanout: 6,
        }
    }
}

/// Exact totals of what `generate` wrote, for verifying scan results.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct GenStats {
    /// Files including the marker file.
    pub files: u64,
    /// Directories below the root.
    pub dirs: u64,
    pub logical_bytes: u64,
}

const EXTENSIONS: &[&str] = &[
    "txt", "jpg", "png", "mp4", "mov", "mp3", "pdf", "docx", "zip", "rs", "ts", "json", "log",
    "dll", "bin", "dat", "",
];

/// Skewed size distribution: mostly tiny files, a few large ones. Kept small
/// overall so a 1,000,000-file tree fits in a few gigabytes.
fn sample_size(rng: &mut Rng) -> u64 {
    match rng.range(0, 999) {
        0..=899 => rng.range(0, 600),
        900..=994 => rng.range(601, 16 * 1024),
        _ => rng.range(16 * 1024 + 1, 1024 * 1024),
    }
}

/// Generates a deterministic tree of `spec.files` files beneath `root`.
/// `root` must not exist or be empty.
pub fn generate(
    root: &Path,
    spec: GenSpec,
    mut on_progress: impl FnMut(u64),
) -> io::Result<GenStats> {
    if root.exists() && fs::read_dir(root)?.next().is_some() {
        return Err(io::Error::new(
            io::ErrorKind::AlreadyExists,
            "fixture root is not empty",
        ));
    }
    fs::create_dir_all(root)?;
    fs::write(root.join(MARKER), b"generated by tessera-testkit\n")?;
    let mut stats = GenStats {
        files: 1,
        dirs: 0,
        logical_bytes: 29,
    };

    let mut rng = Rng::new(spec.seed);
    let mut queue = std::collections::VecDeque::from([root.to_path_buf()]);
    let mut remaining = spec.files;
    let mut name_counter = 0u64;
    while remaining > 0 {
        let Some(dir_path) = queue.pop_front() else {
            break;
        };
        let n_files = rng.range(1, spec.files_per_dir * 2).min(remaining);
        for _ in 0..n_files {
            name_counter += 1;
            let ext = EXTENSIONS[(rng.next_u64() % EXTENSIONS.len() as u64) as usize];
            let name = if ext.is_empty() {
                format!("file_{name_counter}")
            } else {
                format!("file_{name_counter}.{ext}")
            };
            let size = sample_size(&mut rng);
            let f = File::create(dir_path.join(name))?;
            if size > 0 {
                f.set_len(size)?;
            }
            stats.files += 1;
            stats.logical_bytes += size;
        }
        remaining -= n_files;
        if remaining == 0 {
            break;
        }
        let mut n_dirs = rng.range(0, spec.fanout);
        if queue.is_empty() && n_dirs == 0 {
            n_dirs = 1;
        }
        for _ in 0..n_dirs {
            name_counter += 1;
            let d = dir_path.join(format!("dir_{name_counter}"));
            fs::create_dir(&d)?;
            stats.dirs += 1;
            queue.push_back(d);
        }
        on_progress(spec.files - remaining);
    }
    Ok(stats)
}

/// Turns a file into a sparse file of `len` bytes with no data allocated.
#[cfg(windows)]
pub fn make_sparse(path: &Path, len: u64) -> io::Result<()> {
    use std::os::windows::io::AsRawHandle;
    use windows_sys::Win32::System::IO::DeviceIoControl;
    const FSCTL_SET_SPARSE: u32 = 0x0009_00C4;
    let f = fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(path)?;
    let mut returned = 0u32;
    // SAFETY: valid open handle; no input/output buffers; synchronous call.
    let ok = unsafe {
        DeviceIoControl(
            f.as_raw_handle() as _,
            FSCTL_SET_SPARSE,
            std::ptr::null(),
            0,
            std::ptr::null_mut(),
            0,
            &mut returned,
            std::ptr::null_mut(),
        )
    };
    if ok == 0 {
        return Err(io::Error::last_os_error());
    }
    f.set_len(len)
}

#[cfg(unix)]
pub fn make_sparse(path: &Path, len: u64) -> io::Result<()> {
    let f = File::create(path)?;
    f.set_len(len)
}

/// Creates a directory junction (Windows; no administrator rights needed).
#[cfg(windows)]
pub fn junction(link: &Path, target: &Path) -> io::Result<()> {
    let status = std::process::Command::new("cmd")
        .arg("/C")
        .arg("mklink")
        .arg("/J")
        .arg(link)
        .arg(target)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()?;
    if status.success() {
        Ok(())
    } else {
        Err(io::Error::other("mklink /J failed"))
    }
}

/// Creates a directory symbolic link. On Windows this needs Developer Mode
/// or elevation; callers should skip the test if it fails.
pub fn symlink_dir(link: &Path, target: &Path) -> io::Result<()> {
    #[cfg(windows)]
    {
        std::os::windows::fs::symlink_dir(target, link)
    }
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(target, link)
    }
}

/// While alive, denies the current user permission to list `dir`.
#[derive(Debug)]
pub struct DenyListing {
    path: PathBuf,
}

impl DenyListing {
    #[cfg(windows)]
    pub fn new(dir: &Path) -> io::Result<Self> {
        // S-1-1-0 is "Everyone". The owner keeps the right to change the
        // ACL, so the restriction can always be lifted again.
        let status = std::process::Command::new("icacls")
            .arg(dir)
            .args(["/deny", "*S-1-1-0:(OI)(CI)(RX)"])
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()?;
        if !status.success() {
            return Err(io::Error::other("icacls /deny failed"));
        }
        Ok(DenyListing {
            path: dir.to_path_buf(),
        })
    }

    #[cfg(unix)]
    pub fn new(dir: &Path) -> io::Result<Self> {
        use std::os::unix::fs::PermissionsExt;
        // SAFETY: geteuid has no preconditions.
        if unsafe { libc::geteuid() } == 0 {
            return Err(io::Error::other(
                "running as root; permissions are not enforced",
            ));
        }
        fs::set_permissions(dir, fs::Permissions::from_mode(0o000))?;
        Ok(DenyListing {
            path: dir.to_path_buf(),
        })
    }
}

impl Drop for DenyListing {
    fn drop(&mut self) {
        #[cfg(windows)]
        {
            let _ = std::process::Command::new("icacls")
                .arg(&self.path)
                .args(["/remove:d", "*S-1-1-0"])
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .status();
        }
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let _ = fs::set_permissions(&self.path, fs::Permissions::from_mode(0o755));
        }
    }
}
